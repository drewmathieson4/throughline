import { describe, expect, test } from "vitest";
import { categorise, matchStudents, parseDate, parseGradebook, readCell, type ParsedEntry } from "./gradebook";
import { roster } from "./test-roster";

const entry = (p: Partial<ParsedEntry>): ParsedEntry => ({
  line: 2,
  firstName: "Avery",
  lastName: "Quill",
  assignment: "Quiz 1",
  category: null,
  score: 10,
  maxScore: 20,
  dueDate: null,
  position: 0,
  ...p,
});

describe("readCell", () => {
  test.each([
    ["85", { kind: "score", value: 85, max: null, percent: false }],
    ["85.5", { kind: "score", value: 85.5, max: null, percent: false }],
    ["17/20", { kind: "score", value: 17, max: 20, percent: false }],
    ["17 / 20", { kind: "score", value: 17, max: 20, percent: false }],
    ["85%", { kind: "score", value: 85, max: null, percent: true }],
    ["", { kind: "missing" }],
    ["Missing", { kind: "missing" }],
    ["M", { kind: "missing" }],
    ["—", { kind: "missing" }],
    ["Excused", { kind: "excused" }],
    ["EX", { kind: "excused" }],
    ["N/A", { kind: "excused" }],
    ["B+", { kind: "other" }],
    ["see me", { kind: "other" }],
  ])("%s", (cell, expected) => {
    expect(readCell(cell)).toEqual(expected);
  });
});

describe("parseDate", () => {
  test.each([
    ["2026-09-11", "2026-09-11"],
    ["2026-09-11T12:00:00.000Z", "2026-09-11"],
    ["9/11/2026", "2026-09-11"],
    ["9/11/26", "2026-09-11"],
    ["09/01/26", "2026-09-01"],
    ["2026-02-30", null],
    ["11 Sep 2026", null],
    ["", null],
  ])("%s → %s", (cell, expected) => {
    expect(parseDate(cell)).toBe(expected);
  });
});

describe("wide shape", () => {
  // Google Classroom's export: name columns, an email and an overall column, a points row.
  const classroom = [
    ["Last Name", "First Name", "Email Address", "Overall Grade", "Rivers Paragraph", "Quiz 1", "Unit 1 Test"],
    ["", "", "", "Points", "10", "20", "40"],
    ["Quill", "Avery", "avery@example.test", "85.2", "9", "17", "34"],
    ["Marsh", "Alex", "alex@example.test", "60.1", "Missing", "8", "31"],
  ];

  test("reads one entry per student per assignment with the points row as max; skips id, email and overall columns", () => {
    const r = parseGradebook(classroom);
    expect(r.shape).toBe("wide");
    expect(r.skipped).toEqual([]);
    expect(r.guessedMax).toEqual([]);
    expect(r.entries).toHaveLength(6);
    expect(r.entries[0]).toEqual(entry({ line: 3, assignment: "Rivers Paragraph", score: 9, maxScore: 10, position: 0 }));
    expect(r.entries[3]).toEqual(entry({ line: 4, firstName: "Alex", lastName: "Marsh", assignment: "Rivers Paragraph", score: null, maxScore: 10, position: 0 }));
    expect(r.entries[5]).toMatchObject({ assignment: "Unit 1 Test", score: 31, maxScore: 40, position: 2 });
    expect(r.entries.map((e) => e.assignment)).not.toContain("Overall Grade");
  });

  test("reads a date row and ends the table at a narrower line with no name", () => {
    const grid = [
      ["Student", "Quiz 1", "Quiz 2"],
      ["Due", "9/11/26", "2026-09-25"],
      ["Points", "20", "20"],
      ["Avery Quill", "17", "19"],
      [""],
      ["Generated by the grade book"],
    ];
    const r = parseGradebook(grid);
    expect(r.entries.map((e) => [e.assignment, e.dueDate, e.maxScore, e.score])).toEqual([
      ["Quiz 1", "2026-09-11", 20, 17],
      ["Quiz 2", "2026-09-25", 20, 19],
    ]);
    expect(r.skipped).toEqual([]);
  });

  test("guesses the max from x/y cells, 100 for small scores, or the column top, and says which", () => {
    const grid = [
      ["Name", "Map", "Essay", "Big Project"],
      ["Avery Quill", "17/20", "85", "150"],
      ["Alex Marsh", "19/20", "92", "180"],
    ];
    const r = parseGradebook(grid);
    expect(r.entries.filter((e) => e.firstName === "Avery").map((e) => [e.assignment, e.score, e.maxScore])).toEqual([
      ["Map", 17, 20],
      ["Essay", 85, 100],
      ["Big Project", 150, 180],
    ]);
    expect(r.guessedMax).toEqual(["Essay", "Big Project"]);
  });

  test("percent cells are a share of the column's points", () => {
    const r = parseGradebook([
      ["Name", "Quiz"],
      ["Points", "50"],
      ["Avery Quill", "90%"],
    ]);
    expect(r.entries[0]).toMatchObject({ score: 45, maxScore: 50 });
  });

  test("excused cells make no entry; unreadable cells are reported; summary rows are skipped quietly", () => {
    const grid = [
      ["Student", "Quiz 1", "Quiz 2"],
      ["Avery Quill", "EX", "B+"],
      ["Alex Marsh", "15", "16"],
      ["Class average", "15", "16"],
    ];
    const r = parseGradebook(grid);
    expect(r.entries.map((e) => [e.firstName, e.assignment])).toEqual([
      ["Alex", "Quiz 1"],
      ["Alex", "Quiz 2"],
    ]);
    expect(r.skipped).toEqual([{ line: 2, cells: ["Quiz 2", "B+"], reason: "not a score" }]);
  });

  test("reads Last, First names from a single column and title-cases shouting", () => {
    const r = parseGradebook([
      ["Student", "HW 1"],
      ["QUILL, AVERY", "10"],
      ["Marsh, Alex James", "8"],
    ]);
    expect(r.entries.map((e) => `${e.firstName} ${e.lastName}`)).toEqual(["Avery Quill", "Alex Marsh"]);
  });

  test("a column of year groups or ids is not an assignment, so a roster is no grade book", () => {
    const r = parseGradebook([
      ["Last", "First", "Grade", "Student ID"],
      ["Quill", "Avery", "7", "10234"],
    ]);
    expect(r.shape).toBe("none");
    expect(r.entries).toEqual([]);
  });

  test("a column with text under it is not an assignment", () => {
    const r = parseGradebook([
      ["Name", "Group", "Quiz 1"],
      ["Avery Quill", "Athens", "17"],
      ["Alex Marsh", "Sparta", "12"],
    ]);
    expect(r.entries.map((e) => e.assignment)).toEqual(["Quiz 1", "Quiz 1"]);
  });
});

describe("long shape", () => {
  const long = [
    ["Student", "Assignment", "Category", "Score", "Out of", "Due date"],
    ["Quill, Avery", "Quiz 1", "Quizzes", "17", "20", "2026-09-11"],
    ["Marsh, Alex", "Quiz 1", "Quizzes", "Missing", "20", "2026-09-11"],
    ["Quill, Avery", "Timeline", "Projects", "45", "50", "9/25/2026"],
    ["Quill, Avery", "Rivers HW", "", "B", "10", ""],
  ];

  test("reads one entry per row with category, max and date; position is first appearance", () => {
    const r = parseGradebook(long);
    expect(r.shape).toBe("long");
    expect(r.entries).toEqual([
      entry({ line: 2, assignment: "Quiz 1", category: "Quizzes", score: 17, maxScore: 20, dueDate: "2026-09-11", position: 0 }),
      entry({ line: 3, firstName: "Alex", lastName: "Marsh", assignment: "Quiz 1", category: "Quizzes", score: null, maxScore: 20, dueDate: "2026-09-11", position: 0 }),
      entry({ line: 4, assignment: "Timeline", category: "Projects", score: 45, maxScore: 50, dueDate: "2026-09-25", position: 1 }),
    ]);
    expect(r.skipped).toEqual([{ line: 5, cells: ["Rivers HW", "B"], reason: "not a score" }]);
    expect(r.guessedMax).toEqual([]);
  });

  test("without a max column, x/y cells carry the max and plain scores are out of a guessed 100", () => {
    const r = parseGradebook([
      ["Name", "Task", "Points"],
      ["Avery Quill", "Map", "17/20"],
      ["Avery Quill", "Essay", "85"],
      ["Alex Marsh", "Essay", "70"],
    ]);
    expect(r.shape).toBe("long");
    expect(r.entries.map((e) => [e.assignment, e.score, e.maxScore])).toEqual([
      ["Map", 17, 20],
      ["Essay", 85, 100],
      ["Essay", 70, 100],
    ]);
    expect(r.guessedMax).toEqual(["Essay"]);
  });

  test("a wide file whose titles say Assignment and Grade is still wide", () => {
    const r = parseGradebook([
      ["Name", "Assignment 1", "Assignment 2", "Overall Grade"],
      ["Avery Quill", "8", "9", "85"],
    ]);
    expect(r.shape).toBe("wide");
    expect(r.entries.map((e) => e.assignment)).toEqual(["Assignment 1", "Assignment 2"]);
  });

  test("rows without a name or an assignment are reported", () => {
    const r = parseGradebook([
      ["Student", "Assignment", "Score"],
      ["Avery", "Quiz 1", "10"],
      ["Avery Quill", "", "10"],
      ["Avery Quill", "Quiz 1", "10"],
    ]);
    expect(r.skipped.map((s) => [s.line, s.reason])).toEqual([
      [2, "only one name"],
      [3, "no assignment"],
    ]);
    expect(r.entries).toHaveLength(1);
  });
});

describe("categorise", () => {
  test.each([
    ["HW 3: Rivers", "homework"],
    ["Homework week 2", "homework"],
    ["Quiz 1: First Cities", "quiz"],
    ["Pop quiz", "quiz"],
    ["Unit 1 Test", "test"],
    ["Midterm", "test"],
    ["Final exam", "test"],
    ["Timeline Project", "project"],
    ["Warm-up 4", "classwork"],
    ["Exit ticket 9/3", "classwork"],
    ["Participation", "classwork"],
    ["Fertile Crescent Map", null],
    ["Contest", null],
  ])("fixed set: %s → %s", (title, expected) => {
    expect(categorise(title, null)).toBe(expected);
  });

  const syllabus = ["Homework", "Quizzes", "Projects", "Tests"];
  test.each([
    ["Quiz 2: Hammurabi", "Quizzes"],
    ["Unit 1 Test", "Tests"],
    ["Timeline Project", "Projects"],
    ["Hammurabi HW", "Homework"],
    ["Fertile Crescent Map", null],
    ["Warm-up 4", null],
  ])("syllabus names: %s → %s", (title, expected) => {
    expect(categorise(title, syllabus)).toBe(expected);
  });

  test("a syllabus category's own word in the title places it", () => {
    expect(categorise("Formative 2", ["Formative tasks", "Summative tasks"])).toBe("Formative tasks");
    expect(categorise("Lab 3: density", ["Labs", "Tests"])).toBe("Labs");
    expect(categorise("Essay on Athens", ["Essays", "Quizzes"])).toBe("Essays");
    expect(categorise("Reading response", ["Essays", "Quizzes"])).toBe(null);
  });
});

describe("matchStudents", () => {
  test("matches on first and last, then alias and last; reports unmatched lines once", () => {
    const entries = [
      entry({ line: 2, firstName: "avery", lastName: "QUILL" }),
      entry({ line: 3, firstName: "Juni", lastName: "Vale" }),
      entry({ line: 4, firstName: "Nobody", lastName: "Here", assignment: "Quiz 1" }),
      entry({ line: 4, firstName: "Nobody", lastName: "Here", assignment: "Quiz 2" }),
    ];
    const r = matchStudents(entries, roster);
    expect(r.matched.map((e) => e.studentId)).toEqual(["s-avery", "s-juniper"]);
    expect(r.skipped).toEqual([{ line: 4, cells: ["Nobody", "Here"], reason: "not on the roster" }]);
  });
});
